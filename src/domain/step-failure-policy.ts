// V1 fixed policy: transient admission/focus/loading waits are not step failures.
export function postFailureRequiresEnding(reason: string): boolean {
  if (
    /^POST_AI_LABEL_(?:CONFIGURATION_UNAVAILABLE|SETTINGS_CLOSED|CHANGED|CHANGED_AFTER_CONTENT|DOCUMENT_CHANGED|UNCONFIRMED_BEFORE_CONTENT|ACTION_UNCONFIRMED)$/.test(
      reason,
    )
  )
    return true;
  if (
    /^(POST_BACKGROUND_(CHANGED|CONFIGURATION_UNAVAILABLE|UNCONFIRMED|ACTION_UNCONFIRMED|DOCUMENT_CHANGED)|RESOURCE_BACKGROUND_EXECUTOR_REQUIRED)$/.test(
      reason,
    )
  )
    return true;
  if (/^(FACEBOOK_POST_EDITOR_CLOSED|POST_HOME_PREPARATION_INTERRUPTED)$/.test(reason)) return true;
  if (
    /^STORY_(?:NATIVE_RESULT_CONFLICT|ORIGINAL_OBSERVER_REQUIRED|ORIGINAL_PAGE_REQUIRED)$/.test(
      reason,
    )
  )
    return true;
  if (
    /^STORY_(?:EDITOR_CLOSED|FOREIGN_DRAFT|ORIGINAL_TEXT_CHANGED|COMPOSER_ACTION_UNCONFIRMED|FRIENDS_AUDIENCE_UNCONFIRMED|PRIVACY_(?:DIALOG_CLOSED|UNEXPECTED_DIALOG|CHANGED_AFTER_VERIFICATION|CHANGED_AFTER_CONTENT)|SUBMISSION_DOCUMENT_OR_CONTENT_CHANGED|EFFECT_UNCONFIRMED)$/.test(
      reason,
    )
  )
    return true;
  if (/^locator\.(?:click|fill|press|setInputFiles): Timeout \d+ms exceeded\./.test(reason))
    return true;
  return /(?:POST_EFFECT_TIMEOUT|POST_AUDIENCE_(?:CONFIGURATION_UNAVAILABLE|ACTION_UNCONFIRMED)|UPLOAD_STAGE_(?:ROOT_INVALID|RESOURCE_OVERLAP|BUDGET|NO_SPACE|WRITE_INCOMPLETE|CLOSE_FAILED)|PUBLISH_RESULT_UNCONFIRMED|ORIGINAL_SUBMISSION_RESPONSE_UNCONFIRMED|MATERIAL_NO_ELIGIBLE_RESOURCE|OWNED_TAB_(?:CLOSED|LOST|GONE)|TARGET_CLOSED|TAB_CLOSED|PAGE_CLOSED|(?:page|target|context).*closed)/i.test(
    reason,
  );
}
